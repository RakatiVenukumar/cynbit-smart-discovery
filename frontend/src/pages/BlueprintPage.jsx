import { useState, useEffect } from 'react'
import { useLocation, useNavigate } from 'react-router-dom'
import Navbar from '../components/layout/Navbar'
import Footer from '../components/layout/Footer'
import Button from '../components/ui/Button'
import Card from '../components/ui/Card'
import Badge from '../components/ui/Badge'
import { buildDiscoveryPayload } from '../hooks/useDiscovery'
import { generateIdempotencyKey } from '../utils/idempotency'
import { SERVICE_LABEL_MAP } from '../data/services'
import { api } from '../services/api'
import {
  ArrowLeft,
  Send,
  AlertCircle,
  CheckCircle2,
  Clock,
  Layers,
  Cpu,
  Printer,
  Loader2,
  ShieldAlert,
} from 'lucide-react'

export default function BlueprintPage() {
  const location = useLocation()
  const navigate = useNavigate()
  const state = location.state

  const [submitting, setSubmitting] = useState(false)
  const [submitError, setSubmitError] = useState('')
  const [idempotencyKey] = useState(() => generateIdempotencyKey())

  useEffect(() => {
    if (!state || !state.formData || !state.recommendations) {
      navigate('/discover', { replace: true })
    }
  }, [state, navigate])

  if (!state || !state.formData || !state.recommendations) {
    return null
  }

  const { formData, recommendations } = state

  const handleEditRequirements = () => {
    navigate('/discover', { state: { formData } })
  }

  const handleSubmitInquiry = async () => {
    setSubmitting(true)
    setSubmitError('')
    try {
      const discoveryPayload = buildDiscoveryPayload(formData)
      const res = await api.submitInquiry({
        ...discoveryPayload,
        full_name: formData.fullName.trim(),
        email: formData.email.trim(),
        phone: formData.phone ? formData.phone.trim() : null,
        company_name: formData.companyName.trim(),
        consent: formData.consent,
        idempotency_key: idempotencyKey,
      })

      navigate('/success', {
        state: {
          referenceId: res.data.reference_id,
          companyName: formData.companyName,
        },
      })
    } catch (err) {
      const detail = err.response?.data?.detail
      setSubmitError(
        typeof detail === 'string'
          ? detail
          : 'Failed to submit inquiry to the database. Please check that the backend is running.'
      )
    } finally {
      setSubmitting(false)
    }
  }

  const handlePrint = () => {
    window.print()
  }

  return (
    <div className="min-h-screen flex flex-col bg-slate-50">
      <Navbar />

      <main className="flex-1 max-w-5xl w-full mx-auto px-4 sm:px-6 py-8 sm:py-12 space-y-6">
        {/* Disclaimer */}
        <div className="flex items-start gap-3 p-4 rounded-xl bg-blue-50 border border-blue-200 text-blue-900 text-sm">
          <ShieldAlert className="w-5 h-5 shrink-0 text-blue-600 mt-0.5" />
          <div>
            <strong>Preliminary Prototype Recommendations:</strong> The solutions, timelines,
            complexity estimates, and tech stacks below are generated by a deterministic rule
            engine for demonstration purposes only and do not constitute official Cynbit Technologies
            quotations or commitments.
          </div>
        </div>

        {/* Header */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div>
            <Badge variant="cyan" className="mb-2">
              Personalized Project Blueprint
            </Badge>
            <h1 className="text-2xl sm:text-3xl font-bold text-slate-900">
              {formData.companyName} — Digital Solution Roadmap
            </h1>
            <p className="text-sm text-slate-600 mt-1">
              Prepared for {formData.fullName} ({formData.industry})
            </p>
          </div>
          <Button variant="outline" size="sm" onClick={handlePrint} className="gap-1.5 print:hidden">
            <Printer className="w-4 h-4" />
            Print / Save PDF
          </Button>
        </div>

        {/* Business & Constraints Summary */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-5">
          <Card>
            <h2 className="text-sm font-bold uppercase tracking-wider text-slate-500 mb-3">
              Business Requirements Summary
            </h2>
            <dl className="space-y-2 text-sm">
              <div className="flex justify-between gap-4">
                <dt className="text-slate-500">Industry</dt>
                <dd className="font-medium text-slate-900 text-right">{formData.industry}</dd>
              </div>
              <div className="flex justify-between gap-4">
                <dt className="text-slate-500">Team Size</dt>
                <dd className="font-medium text-slate-900 text-right">{formData.businessSize}</dd>
              </div>
              <div className="flex justify-between gap-4">
                <dt className="text-slate-500">Stage</dt>
                <dd className="font-medium text-slate-900 text-right">{formData.businessStage}</dd>
              </div>
              <div className="flex justify-between gap-4">
                <dt className="text-slate-500">Digital Presence</dt>
                <dd className="font-medium text-slate-900 text-right">{formData.digitalPresence}</dd>
              </div>
            </dl>
            <div className="mt-4 pt-3 border-t border-slate-100">
              <p className="text-xs font-semibold text-slate-500 mb-1.5">Selected Services</p>
              <div className="flex flex-wrap gap-1.5">
                {formData.selectedServices.map((id) => (
                  <Badge key={id} variant="blue">
                    {SERVICE_LABEL_MAP[id] || id}
                  </Badge>
                ))}
              </div>
            </div>
          </Card>

          <Card>
            <h2 className="text-sm font-bold uppercase tracking-wider text-slate-500 mb-3">
              Budget &amp; Delivery Preferences
            </h2>
            <dl className="space-y-2 text-sm">
              <div className="flex justify-between gap-4">
                <dt className="text-slate-500">Indicative Budget</dt>
                <dd className="font-medium text-slate-900 text-right">{formData.budgetRange}</dd>
              </div>
              <div className="flex justify-between gap-4">
                <dt className="text-slate-500">Target Timeline</dt>
                <dd className="font-medium text-slate-900 text-right">{formData.timeline}</dd>
              </div>
              <div className="flex justify-between gap-4">
                <dt className="text-slate-500">Urgency</dt>
                <dd className="font-medium text-slate-900 text-right">{formData.urgency}</dd>
              </div>
              <div className="flex justify-between gap-4">
                <dt className="text-slate-500">Readiness</dt>
                <dd className="font-medium text-slate-900 text-right">
                  {formData.projectReadiness}
                </dd>
              </div>
            </dl>
            {formData.businessGoals.length > 0 && (
              <div className="mt-4 pt-3 border-t border-slate-100">
                <p className="text-xs font-semibold text-slate-500 mb-1.5">Primary Goals</p>
                <p className="text-xs text-slate-700">{formData.businessGoals.join(' · ')}</p>
              </div>
            )}
          </Card>
        </div>

        {/* Recommendations */}
        <div className="space-y-5">
          <h2 className="text-xl font-bold text-slate-900">
            Recommended Solutions ({recommendations.length})
          </h2>

          {recommendations.map((rec, index) => (
            <Card key={`${rec.solution_name}-${index}`} padding="p-6 sm:p-7">
              <div className="flex flex-wrap items-start justify-between gap-3 mb-4">
                <div>
                  <Badge variant="blue" className="mb-2">
                    {rec.recommended_service}
                  </Badge>
                  <h3 className="text-xl font-bold text-slate-900">{rec.solution_name}</h3>
                </div>
                <div className="flex items-center gap-2">
                  <span className="inline-flex items-center gap-1 px-2.5 py-1 rounded-lg bg-slate-100 text-slate-700 text-xs font-medium">
                    <Clock className="w-3.5 h-3.5" />
                    {rec.indicative_timeline}
                  </span>
                  <Badge
                    variant={
                      rec.complexity_level === 'high'
                        ? 'high'
                        : rec.complexity_level === 'medium'
                        ? 'medium'
                        : 'low'
                    }
                  >
                    Complexity: {rec.complexity_level}
                  </Badge>
                </div>
              </div>

              <p className="text-sm text-slate-700 leading-relaxed mb-6 bg-slate-50 p-4 rounded-lg border border-slate-100">
                {rec.reasoning}
              </p>

              <div className="grid grid-cols-1 md:grid-cols-2 gap-6 mb-6">
                <div>
                  <h4 className="text-xs font-bold uppercase tracking-wider text-slate-500 mb-2.5 flex items-center gap-1.5">
                    <CheckCircle2 className="w-4 h-4 text-blue-600" />
                    Suggested Features
                  </h4>
                  <ul className="space-y-1.5 text-sm text-slate-700">
                    {(rec.suggested_features || []).map((feat) => (
                      <li key={feat} className="flex items-start gap-2">
                        <span className="text-blue-600 mt-1">•</span>
                        <span>{feat}</span>
                      </li>
                    ))}
                  </ul>
                </div>

                <div>
                  <h4 className="text-xs font-bold uppercase tracking-wider text-slate-500 mb-2.5 flex items-center gap-1.5">
                    <Cpu className="w-4 h-4 text-cyan-600" />
                    Suggested Technology Stack
                  </h4>
                  <div className="flex flex-wrap gap-2">
                    {(rec.suggested_tech_stack || []).map((tech) => (
                      <span
                        key={tech}
                        className="px-2.5 py-1 rounded-md bg-slate-100 border border-slate-200 text-xs font-medium text-slate-800"
                      >
                        {tech}
                      </span>
                    ))}
                  </div>
                </div>
              </div>

              <div>
                <h4 className="text-xs font-bold uppercase tracking-wider text-slate-500 mb-2.5 flex items-center gap-1.5">
                  <Layers className="w-4 h-4 text-indigo-600" />
                  Implementation Roadmap
                </h4>
                <ol className="space-y-2">
                  {(rec.implementation_roadmap || []).map((phase, pIdx) => (
                    <li
                      key={phase}
                      className="flex items-start gap-3 text-sm text-slate-700 bg-slate-50/70 px-3.5 py-2.5 rounded-lg border border-slate-100"
                    >
                      <span className="w-5 h-5 rounded-full bg-blue-100 text-blue-700 text-xs font-bold flex items-center justify-center shrink-0 mt-0.5">
                        {pIdx + 1}
                      </span>
                      <span>{phase}</span>
                    </li>
                  ))}
                </ol>
              </div>
            </Card>
          ))}
        </div>

        {submitError && (
          <div
            role="alert"
            className="flex items-start gap-3 p-4 rounded-xl bg-red-50 border border-red-200 text-red-800 text-sm"
          >
            <AlertCircle className="w-5 h-5 shrink-0 text-red-600 mt-0.5" />
            <span>{submitError}</span>
          </div>
        )}

        {/* Actions */}
        <Card className="print:hidden" padding="p-5">
          <div className="flex flex-col sm:flex-row items-center justify-between gap-4">
            <Button
              variant="secondary"
              onClick={handleEditRequirements}
              disabled={submitting}
              className="w-full sm:w-auto gap-1.5"
            >
              <ArrowLeft className="w-4 h-4" />
              Edit Requirements
            </Button>

            <Button
              onClick={handleSubmitInquiry}
              disabled={submitting}
              size="lg"
              className="w-full sm:w-auto gap-2"
            >
              {submitting ? (
                <>
                  <Loader2 className="w-4 h-4 animate-spin" />
                  Submitting Inquiry...
                </>
              ) : (
                <>
                  Submit Structured Inquiry
                  <Send className="w-4 h-4" />
                </>
              )}
            </Button>
          </div>
        </Card>
      </main>

      <Footer />
    </div>
  )
}
